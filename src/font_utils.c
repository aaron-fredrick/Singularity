void draw_char_colored(img_t *img, char c, uint32_t x, uint32_t y, uint32_t color) {
    const uint8_t *glyph;
    if (c >= ' ' && c <= '~') {
        glyph = font_data[c - ' '];
    } else {
        glyph = font_data[0]; // space
    }
    
    for (int col = 0; col < 5; col++) {
        uint8_t column = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (column & (1 << row)) {
               if (x + col < img->width && y + row < img->height) {
                   img->data[(y + row) * img->width + (x + col)] = color;
               }
            }
        }
    }
}

void draw_char(img_t *img, char c, uint32_t x, uint32_t y) {
    draw_char_colored(img, c, x, y, 0xFFFFFFFF); // Default white
}

void draw_char_dynamic(img_t *img, char c, uint32_t x, uint32_t y, int primary_channel) {
    const uint8_t *glyph;
    if (c >= ' ' && c <= '~') glyph = font_data[c - ' '];
    else glyph = font_data[0];

    for (int col = 0; col < 5; col++) {
        uint8_t column = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (column & (1 << row)) {
                int px = x + col;
                int py = y + row;
                if ((uint32_t)px < img->width && (uint32_t)py < img->height) {
                    uint8_t tr, tg, tb;
                    channel_color(img, px, py, primary_channel, &tr, &tg, &tb);
                    img->data[py * img->width + px] = (0xFF << 24) | (tr << 16) | (tg << 8) | tb;
                }
            }
        }
    }
}

void draw_string_colored(img_t *img, const char *str, uint32_t x, uint32_t y, uint32_t color) {
    size_t len = strlen(str);
    for (size_t i = 0; i < len; i++) {
        draw_char_colored(img, str[i], x + (i * 6), y, color); 
    }
}

void draw_string_dynamic(img_t *img, const char *str, uint32_t x, uint32_t y, int primary_channel) {
    size_t len = strlen(str);
    for (size_t i = 0; i < len; i++) {
        draw_char_dynamic(img, str[i], x + (i * 6), y, primary_channel);
    }
}

void draw_string(img_t *img, const char *str, uint32_t x, uint32_t y) {
    draw_string_colored(img, str, x, y, 0xFFFFFFFF);
}
